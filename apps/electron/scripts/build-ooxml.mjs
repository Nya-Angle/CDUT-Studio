import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const appRoot = path.resolve(scriptDir, '..')
// 通过 Node 标准解析定位 @silurus/ooxml 的 dist 目录，
// 兼容 bun hoisted 布局在根 node_modules 与嵌套 node_modules 两种形态。
const require = createRequire(path.join(appRoot, 'package.json'))
const sourceDir = path.dirname(require.resolve('@silurus/ooxml'))
const publicDir = path.join(appRoot, 'src', 'renderer', 'public', 'vendor', 'ooxml')

// 解析失败时回退到逐级向上查找（Bun workspace 会把依赖 hoist 到 monorepo 顶层）。
if (!fs.existsSync(sourceDir)) {
  const checked = []
  let from = appRoot
  let found
  for (;;) {
    const dist = path.join(from, 'node_modules', '@silurus', 'ooxml', 'dist')
    checked.push(dist)
    if (fs.existsSync(dist)) { found = dist; break }
    const parent = path.dirname(from)
    if (parent === from) break
    from = parent
  }
  if (!found) {
    throw new Error(`@silurus/ooxml dist 目录不存在；已尝试：\\n${checked.join('\\n')}`)
  }
  sourceDir = found
}

fs.rmSync(publicDir, { recursive: true, force: true })
fs.mkdirSync(publicDir, { recursive: true })

for (const entry of fs.readdirSync(sourceDir, { withFileTypes: true })) {
  const source = path.join(sourceDir, entry.name)
  const target = path.join(publicDir, entry.name)
  fs.cpSync(source, target, { recursive: true })
}

const manifest = {}
for (const format of ['docx', 'xlsx', 'pptx']) {
  const source = path.join(sourceDir, `${format}_parser_bg.wasm`)
  const bytes = fs.readFileSync(source)
  const hash = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 16)
  const hashedName = `${format}_parser_bg.${hash}.wasm`
  fs.copyFileSync(source, path.join(publicDir, hashedName))
  manifest[format] = hashedName
}

fs.writeFileSync(
  path.join(publicDir, 'wasm-manifest.mjs'),
  `// Generated by scripts/build-ooxml.mjs. Do not edit.\nexport default ${JSON.stringify(manifest, null, 2)};\n`,
)

const copiedFiles = fs.readdirSync(publicDir).length
console.log(`[ooxml] copied ${copiedFiles} files to src/renderer/public/vendor/ooxml`)
console.log(`[ooxml] wasm manifest: ${JSON.stringify(manifest)}`)
